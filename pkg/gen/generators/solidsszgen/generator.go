package solidsszgen

import (
	"fmt"
	"strings"

	"github.com/dave/jennifer/jen"
	"github.com/gfx-labs/cuessz"
	"github.com/gfx-labs/ssz/pkg/dag"
)

// GeneratorContext holds all the context needed for code generation
type GeneratorContext struct {
	// Defs holds all the type definitions from the schema
	Defs map[string]cuessz.Def

	// Future options can be added here:
	// PackageName string
	// UsePointers bool
	// GenerateHelpers bool
	// etc.
}

// GenerateCode generates Go code from cuessz definitions, returning one file per type
func GenerateCode(packageName string, defs map[string]cuessz.Def) (map[string]*jen.File, error) {
	ctx := &GeneratorContext{
		Defs: defs,
	}
	return GenerateCodeWithContext(packageName, ctx)
}

// GenerateCodeWithContext generates Go code using a generator context
func GenerateCodeWithContext(packageName string, ctx *GeneratorContext) (map[string]*jen.File, error) {
	files := make(map[string]*jen.File)

	// First pass: collect list types that need to be generated from container fields
	listTypesToGenerate := make(map[string]cuessz.Def)
	for _, defName := range dag.TopologicalSort(ctx.Defs) {
		def := ctx.Defs[defName]
		if def.Type == cuessz.TypeContainer {
			for _, field := range def.Children {
				if field.Def.Type == cuessz.TypeList && len(field.Def.Children) > 0 {
					// Generate a list type for this field if it's a list of variable-size elements
					elemDef := field.Def.Children[0].Def
					if !isFixedSize(elemDef, ctx) {
						// Create a name for this list type
						listTypeName := snakeToCamel(field.Name) + "List"
						// If it's a ref, use the referenced type name
						if elemDef.Type == cuessz.TypeRef && elemDef.Ref != "" {
							listTypeName = elemDef.Ref + "List"
						}
						// Only add if not already defined
						if _, exists := ctx.Defs[listTypeName]; !exists && listTypesToGenerate[listTypeName].Type == "" {
							listTypesToGenerate[listTypeName] = field.Def
						}
					}
				}
			}
		}
	}

	// Sort def names by dependency order
	defNames := dag.TopologicalSort(ctx.Defs)

	// Generate code for each def in sorted order
	for _, defName := range defNames {
		def := ctx.Defs[defName]

		// Create a new file for this type
		f := jen.NewFile(packageName)

		// Add generated code comment
		f.HeaderComment("Code generated by genssz solidssz. DO NOT EDIT.")

		// Add imports
		f.ImportName("github.com/gfx-labs/ssz/pkg/solidssz", "solidssz")
		f.ImportName("encoding/binary", "binary")

		// Generate based on type
		var err error
		switch def.Type {
		case cuessz.TypeContainer:
			// Check if it's fixed or variable size
			isFixed := isFixedSize(def, ctx)
			if isFixed {
				err = generateFixedContainer(f, defName, def, ctx)
			} else {
				err = generateVariableContainerWithBuilder(f, defName, def, ctx)
			}
		case cuessz.TypeVector:
			// Check if elements are fixed or variable size
			if len(def.Children) > 0 && !isFixedSize(def.Children[0].Def, ctx) {
				err = generateVariableElementVector(f, defName, def, ctx)
			} else {
				// Fixed-size vectors are handled as containers
				err = generateFixedContainer(f, defName, def, ctx)
			}
		case cuessz.TypeList, cuessz.TypeBitList:
			err = generateList(f, defName, def, ctx)
		case cuessz.TypeRef:
			// Type aliases are handled differently in solidssz
			continue
		default:
			// Skip other types for now
			continue
		}

		if err != nil {
			return nil, fmt.Errorf("failed to generate %s: %w", defName, err)
		}

		files[defName] = f
	}

	// Generate list types for container fields
	for listTypeName, listDef := range listTypesToGenerate {
		f := jen.NewFile(packageName)
		f.HeaderComment("Code generated by genssz solidssz. DO NOT EDIT.")
		f.ImportName("github.com/gfx-labs/ssz/pkg/solidssz", "solidssz")
		f.ImportName("encoding/binary", "binary")
		f.ImportName("fmt", "fmt")

		err := generateList(f, listTypeName, listDef, ctx)
		if err != nil {
			return nil, fmt.Errorf("failed to generate list type %s: %w", listTypeName, err)
		}

		files[listTypeName] = f
	}

	return files, nil
}

// isFixedSize checks if a def is fixed size (no variable-length fields)
func isFixedSize(def cuessz.Def, ctx *GeneratorContext) bool {
	switch def.Type {
	case cuessz.TypeBoolean, cuessz.TypeUint8, cuessz.TypeUint16, cuessz.TypeUint32, cuessz.TypeUint64, cuessz.TypeUint128, cuessz.TypeUint256:
		return true
	case cuessz.TypeBitVector:
		return true
	case cuessz.TypeVector:
		// Vectors are fixed-size only if their elements are fixed-size
		if len(def.Children) == 0 {
			return false // No element type specified
		}
		return isFixedSize(def.Children[0].Def, ctx)
	case cuessz.TypeBitList, cuessz.TypeList:
		return false
	case cuessz.TypeContainer:
		// Check all children
		for _, child := range def.Children {
			if !isFixedSize(child.Def, ctx) {
				return false
			}
		}
		return true
	case cuessz.TypeRef:
		if refDef, ok := ctx.Defs[def.Ref]; ok {
			return isFixedSize(refDef, ctx)
		}
		return false
	default:
		return false
	}
}

// generateFixedContainer generates code for a fixed-size container
func generateFixedContainer(f *jen.File, defName string, def cuessz.Def, ctx *GeneratorContext) error {
	// Calculate field offsets and total size
	offsets, totalSize, err := calculateOffsets(def, ctx)
	if err != nil {
		return fmt.Errorf("failed to calculate offsets: %w", err)
	}

	// Generate type comment
	f.Comment(fmt.Sprintf("%s is a fixed-size SSZ container with the following byte layout:", defName))
	f.Comment("")
	f.Comment("Byte layout:")
	for i, child := range def.Children {
		offset := offsets[i]
		size, _ := calculateFieldSize(child.Def, ctx)
		endOffset := offset + size - 1
		typeDesc := getTypeDescription(child.Def)

		if offset == endOffset {
			f.Comment(fmt.Sprintf("[%3d]      %s (%s)", offset, child.Name, typeDesc))
		} else {
			f.Comment(fmt.Sprintf("[%3d-%3d]  %s (%s)", offset, endOffset, child.Name, typeDesc))
		}
	}
	f.Comment(fmt.Sprintf("Total size: %d bytes", totalSize))

	// Generate type definition
	f.Type().Id(defName).Op("[]").Byte()
	f.Line()

	// Generate constructor
	f.Comment(fmt.Sprintf("New%s creates a new %s", defName, defName))
	f.Func().Id(fmt.Sprintf("New%s", defName)).Params().Id(defName).Block(
		jen.Return(jen.Make(jen.Op("[]").Byte(), jen.Lit(int(totalSize)))),
	)
	f.Line()

	// Generate NewFromSSZ constructor
	f.Comment(fmt.Sprintf("New%sFromSSZ creates a %s from SSZ-encoded bytes", defName, defName))
	f.Func().Id(fmt.Sprintf("New%sFromSSZ", defName)).Params(jen.Id("data").Op("[]").Byte()).Id(defName).Block(
		jen.If(jen.Len(jen.Id("data")).Op("!=").Lit(int(totalSize))).Block(
			jen.Comment("Invalid data: incorrect size for fixed container"),
			jen.Return(jen.Nil()),
		),
		jen.Id("s").Op(":=").Make(jen.Op("[]").Byte(), jen.Lit(int(totalSize))),
		jen.Copy(jen.Id("s"), jen.Id("data")),
		jen.Return(jen.Id(defName).Call(jen.Id("s"))),
	)
	f.Line()

	// Fixed() method
	f.Func().Params(jen.Id("s").Id(defName)).Id("Fixed").Params().Bool().Block(
		jen.Return(jen.True()),
	)
	f.Line()

	// SizeSSZ() method
	f.Func().Params(jen.Id("s").Id(defName)).Id("SizeSSZ").Params().Int().Block(
		jen.Return(jen.Lit(int(totalSize))),
	)
	f.Line()

	// MarshalSSZ() method
	f.Func().Params(jen.Id("s").Id(defName)).Id("MarshalSSZ").Params().Params(jen.Op("[]").Byte(), jen.Error()).Block(
		jen.If(jen.Len(jen.Id("s")).Op("!=").Id("s").Dot("SizeSSZ").Call()).Block(
			jen.Return(jen.Nil(), jen.Qual("fmt", "Errorf").Call(
				jen.Lit("size mismatch: expected %d, got %d"),
				jen.Id("s").Dot("SizeSSZ").Call(),
				jen.Len(jen.Id("s")),
			)),
		),
		jen.Return(jen.Id("s"), jen.Nil()),
	)
	f.Line()

	// Generate getters and setters
	for i, child := range def.Children {
		offset := offsets[i]
		size, _ := calculateFieldSize(child.Def, ctx)
		generateGetter(f, defName, child, offset, size, ctx)
		generateSetter(f, defName, child, offset, size, ctx)
	}

	return nil
}

// calculateOffsets calculates byte offsets for all fields
func calculateOffsets(def cuessz.Def, ctx *GeneratorContext) ([]uint64, uint64, error) {
	offsets := make([]uint64, len(def.Children))
	currentOffset := uint64(0)

	for i, child := range def.Children {
		offsets[i] = currentOffset
		size, err := calculateFieldSize(child.Def, ctx)
		if err != nil {
			return nil, 0, fmt.Errorf("failed to calculate size of field %s: %w", child.Name, err)
		}
		currentOffset += size
	}

	return offsets, currentOffset, nil
}

// calculateFieldSize calculates the byte size of a def (only for fixed-size types)
func calculateFieldSize(def cuessz.Def, ctx *GeneratorContext) (uint64, error) {
	// First check if it's fixed size
	if !isFixedSize(def, ctx) {
		return 0, fmt.Errorf("cannot calculate size of %s (not fixed size)", def.Type)
	}

	switch def.Type {
	case cuessz.TypeUint8, cuessz.TypeBoolean:
		return 1, nil
	case cuessz.TypeUint16:
		return 2, nil
	case cuessz.TypeUint32:
		return 4, nil
	case cuessz.TypeUint64:
		return 8, nil
	case cuessz.TypeUint128:
		return 16, nil
	case cuessz.TypeUint256:
		return 32, nil
	case cuessz.TypeBitVector:
		return (def.Size + 7) / 8, nil
	case cuessz.TypeVector:
		if len(def.Children) == 0 {
			return 0, fmt.Errorf("vector missing element type")
		}
		elemSize, err := calculateFieldSize(def.Children[0].Def, ctx)
		if err != nil {
			return 0, err
		}
		return elemSize * def.Size, nil
	case cuessz.TypeContainer:
		_, totalSize, err := calculateOffsets(def, ctx)
		return totalSize, err
	case cuessz.TypeRef:
		refDef, ok := ctx.Defs[def.Ref]
		if !ok {
			return 0, fmt.Errorf("ref type '%s' not found", def.Ref)
		}
		return calculateFieldSize(refDef, ctx)
	default:
		return 0, fmt.Errorf("cannot calculate size of %s (not fixed size)", def.Type)
	}
}

// getTypeDescription returns a human-readable description of a type
func getTypeDescription(def cuessz.Def) string {
	switch def.Type {
	case cuessz.TypeUint8, cuessz.TypeUint16, cuessz.TypeUint32, cuessz.TypeUint64, cuessz.TypeUint128, cuessz.TypeUint256, cuessz.TypeBoolean:
		return string(def.Type)
	case cuessz.TypeBitVector:
		return fmt.Sprintf("bitvector[%d]", def.Size)
	case cuessz.TypeVector:
		if len(def.Children) > 0 && def.Children[0].Def.Type == cuessz.TypeUint8 {
			return fmt.Sprintf("bytevector[%d]", def.Size)
		}
		return fmt.Sprintf("vector[%d]", def.Size)
	case cuessz.TypeContainer:
		return "container"
	case cuessz.TypeRef:
		return fmt.Sprintf("ref(%s)", def.Ref)
	default:
		return string(def.Type)
	}
}

// getElementTypeName returns the clean type name for documentation (without ref wrapper)
func getElementTypeName(def cuessz.Def, ctx *GeneratorContext) string {
	switch def.Type {
	case cuessz.TypeRef:
		// Just return the referenced type name, not "ref(TypeName)"
		return def.Ref
	case cuessz.TypeUint8:
		return "byte"
	case cuessz.TypeUint16, cuessz.TypeUint32, cuessz.TypeUint64, cuessz.TypeUint128, cuessz.TypeUint256:
		return string(def.Type)
	case cuessz.TypeBoolean:
		return "bool"
	case cuessz.TypeContainer:
		return "container"
	case cuessz.TypeBitVector:
		return fmt.Sprintf("bitvector[%d]", def.Size)
	case cuessz.TypeBitList:
		return fmt.Sprintf("bitlist[%d]", def.Limit)
	case cuessz.TypeVector:
		if len(def.Children) > 0 {
			elemType := getElementTypeName(def.Children[0].Def, ctx)
			return fmt.Sprintf("vector[%s, %d]", elemType, def.Size)
		}
		return fmt.Sprintf("vector[%d]", def.Size)
	case cuessz.TypeList:
		if len(def.Children) > 0 {
			elemType := getElementTypeName(def.Children[0].Def, ctx)
			return fmt.Sprintf("list[%s, %d]", elemType, def.Limit)
		}
		return fmt.Sprintf("list[%d]", def.Limit)
	default:
		return string(def.Type)
	}
}

// generateGetter generates a getter method for a field
func generateGetter(f *jen.File, typeName string, field cuessz.Field, offset, size uint64, ctx *GeneratorContext) {
	capitalName := capitalize(field.Name)

	// Determine return type based on the actual field type
	def := field.Def

	// Resolve refs to get the actual type
	if def.Type == cuessz.TypeRef {
		if refDef, ok := ctx.Defs[def.Ref]; ok {
			def = refDef
		}
	}

	var returnType *jen.Statement
	switch def.Type {
	case cuessz.TypeBoolean:
		returnType = jen.Bool()
	case cuessz.TypeUint8:
		returnType = jen.Uint8()
	case cuessz.TypeUint16:
		returnType = jen.Uint16()
	case cuessz.TypeUint32:
		returnType = jen.Uint32()
	case cuessz.TypeUint64:
		returnType = jen.Uint64()
	case cuessz.TypeBitVector, cuessz.TypeVector, cuessz.TypeContainer:
		// Return fixed-size array
		returnType = jen.Index(jen.Lit(int(size))).Byte()
	default:
		returnType = jen.Op("[]").Byte()
	}

	// Generate getter
	f.Func().Params(jen.Id("s").Id(typeName)).Id(capitalName).Params().Add(returnType).Block(
		generateGetterBody(field.Def, offset, size),
	)
	f.Line()
}

// generateGetterBody generates the body of a getter method
func generateGetterBody(def cuessz.Def, offset, size uint64) *jen.Statement {
	endOffset := offset + size

	switch def.Type {
	case cuessz.TypeBoolean:
		return jen.Return(jen.Id("s").Index(jen.Lit(int(offset))).Op("!=").Lit(0))
	case cuessz.TypeUint8:
		return jen.Return(jen.Id("s").Index(jen.Lit(int(offset))))
	case cuessz.TypeUint16:
		return jen.Return(jen.Qual("encoding/binary", "LittleEndian").Dot("Uint16").Call(
			jen.Id("s").Index(jen.Lit(int(offset)).Op(":").Lit(int(endOffset))),
		))
	case cuessz.TypeUint32:
		return jen.Return(jen.Qual("encoding/binary", "LittleEndian").Dot("Uint32").Call(
			jen.Id("s").Index(jen.Lit(int(offset)).Op(":").Lit(int(endOffset))),
		))
	case cuessz.TypeUint64:
		return jen.Return(jen.Qual("encoding/binary", "LittleEndian").Dot("Uint64").Call(
			jen.Id("s").Index(jen.Lit(int(offset)).Op(":").Lit(int(endOffset))),
		))
	default:
		// bitvector, vector, etc.
		return jen.Block(
			jen.Var().Id("v").Index(jen.Lit(int(size))).Byte(),
			jen.Copy(jen.Id("v").Index(jen.Op(":")), jen.Id("s").Index(jen.Lit(int(offset)).Op(":").Lit(int(endOffset)))),
			jen.Return(jen.Id("v")),
		)
	}
}

// generateSetter generates a setter method for a field
func generateSetter(f *jen.File, typeName string, field cuessz.Field, offset, size uint64, ctx *GeneratorContext) {
	capitalName := capitalize(field.Name)

	// Determine parameter type based on the actual field type
	def := field.Def

	// Resolve refs to get the actual type
	if def.Type == cuessz.TypeRef {
		if refDef, ok := ctx.Defs[def.Ref]; ok {
			def = refDef
		}
	}

	var paramType *jen.Statement
	switch def.Type {
	case cuessz.TypeBoolean:
		paramType = jen.Bool()
	case cuessz.TypeUint8:
		paramType = jen.Uint8()
	case cuessz.TypeUint16:
		paramType = jen.Uint16()
	case cuessz.TypeUint32:
		paramType = jen.Uint32()
	case cuessz.TypeUint64:
		paramType = jen.Uint64()
	case cuessz.TypeBitVector, cuessz.TypeVector, cuessz.TypeContainer:
		// Accept fixed-size array
		paramType = jen.Index(jen.Lit(int(size))).Byte()
	default:
		paramType = jen.Op("[]").Byte()
	}

	// Generate setter
	f.Func().Params(jen.Id("s").Id(typeName)).Id(fmt.Sprintf("Set%s", capitalName)).Params(
		jen.Id("v").Add(paramType),
	).Block(
		generateSetterBody(field.Def, offset, size),
	)
	f.Line()
}

// generateSetterBody generates the body of a setter method
func generateSetterBody(def cuessz.Def, offset, size uint64) *jen.Statement {
	endOffset := offset + size

	switch def.Type {
	case cuessz.TypeBoolean:
		return jen.If(jen.Id("v")).Block(
			jen.Id("s").Index(jen.Lit(int(offset))).Op("=").Lit(1),
		).Else().Block(
			jen.Id("s").Index(jen.Lit(int(offset))).Op("=").Lit(0),
		)
	case cuessz.TypeUint8:
		return jen.Id("s").Index(jen.Lit(int(offset))).Op("=").Id("v")
	case cuessz.TypeUint16:
		return jen.Qual("encoding/binary", "LittleEndian").Dot("PutUint16").Call(
			jen.Id("s").Index(jen.Lit(int(offset)).Op(":").Lit(int(endOffset))),
			jen.Id("v"),
		)
	case cuessz.TypeUint32:
		return jen.Qual("encoding/binary", "LittleEndian").Dot("PutUint32").Call(
			jen.Id("s").Index(jen.Lit(int(offset)).Op(":").Lit(int(endOffset))),
			jen.Id("v"),
		)
	case cuessz.TypeUint64:
		return jen.Qual("encoding/binary", "LittleEndian").Dot("PutUint64").Call(
			jen.Id("s").Index(jen.Lit(int(offset)).Op(":").Lit(int(endOffset))),
			jen.Id("v"),
		)
	default:
		// bitvector, vector, etc.
		return jen.Copy(jen.Id("s").Index(jen.Lit(int(offset)).Op(":").Lit(int(endOffset))), jen.Id("v").Index(jen.Op(":")))
	}
}

// capitalize capitalizes the first letter of a string
func capitalize(s string) string {
	if len(s) == 0 {
		return s
	}
	return strings.ToUpper(s[:1]) + s[1:]
}

// snakeToCamel converts snake_case to CamelCase
func snakeToCamel(s string) string {
	parts := strings.Split(s, "_")
	for i, part := range parts {
		if len(part) > 0 {
			parts[i] = strings.ToUpper(part[:1]) + part[1:]
		}
	}
	return strings.Join(parts, "")
}

// toPrivateFieldName converts a field name to a private field name
func toPrivateFieldName(name string) string {
	camel := snakeToCamel(name)
	if len(camel) == 0 {
		return camel
	}
	return strings.ToLower(camel[:1]) + camel[1:]
}

// generateVariableElementVector generates code for a vector with variable-size elements
func generateVariableElementVector(f *jen.File, defName string, def cuessz.Def, ctx *GeneratorContext) error {
	if len(def.Children) == 0 {
		return fmt.Errorf("vector missing element type")
	}

	// elemDef := def.Children[0].Def // TODO: Use for type information
	vectorSize := def.Size

	// Calculate fixed portion size (offsets for each element)
	fixedSize := uint64(vectorSize * 4) // 4 bytes per offset

	// Generate type comment
	f.Comment(fmt.Sprintf("%s is a vector[%d] with variable-size elements", defName, vectorSize))
	f.Comment("Fixed chunk contains offsets for each element")
	f.Comment("Each element is stored separately")
	f.Line()

	// Generate struct definition with private fields
	structFields := []jen.Code{
		jen.Id("fixedChunk").Op("[]").Byte().Comment(fmt.Sprintf("%d offsets", vectorSize)),
	}

	// Add a private field for each element
	for i := uint64(0); i < vectorSize; i++ {
		fieldName := fmt.Sprintf("element%d", i)
		structFields = append(structFields, jen.Id(fieldName).Op("[]").Byte())
	}

	f.Type().Id(defName).Struct(structFields...)
	f.Line()

	// Generate constructor
	f.Comment(fmt.Sprintf("New%s creates a new %s", defName, defName))
	constructorBlock := []jen.Code{
		jen.Id("s").Op(":=").Op("&").Id(defName).Values(
			jen.Id("fixedChunk").Op(":").Make(jen.Op("[]").Byte(), jen.Lit(int(fixedSize))),
		),
		jen.Line(),
		jen.Comment(fmt.Sprintf("Initialize offsets for %d elements - all point to end of fixed chunk", vectorSize)),
	}

	// Initialize all offsets to point to the end of fixed chunk (since all elements start empty)
	initialOffset := fixedSize
	for i := uint64(0); i < vectorSize; i++ {
		offsetPos := uint64(i * 4)
		constructorBlock = append(constructorBlock,
			jen.Qual("encoding/binary", "LittleEndian").Dot("PutUint32").Call(
				jen.Id("s").Dot("fixedChunk").Index(jen.Lit(int(offsetPos)).Op(":").Lit(int(offsetPos+4))),
				jen.Uint32().Call(jen.Lit(int(initialOffset))),
			),
		)
	}

	constructorBlock = append(constructorBlock, jen.Return(jen.Id("s")))

	f.Func().Id(fmt.Sprintf("New%s", defName)).Params().Op("*").Id(defName).Block(constructorBlock...)
	f.Line()

	// Fixed() method
	f.Func().Params(jen.Id("s").Op("*").Id(defName)).Id("Fixed").Params().Bool().Block(
		jen.Return(jen.False()),
	)
	f.Line()

	// SizeSSZ() method - calculates dynamically
	sizeBlock := []jen.Code{
		jen.Id("size").Op(":=").Len(jen.Id("s").Dot("fixedChunk")),
	}
	for i := uint64(0); i < vectorSize; i++ {
		fieldName := fmt.Sprintf("element%d", i)
		sizeBlock = append(sizeBlock,
			jen.Id("size").Op("+=").Len(jen.Id("s").Dot(fieldName)),
		)
	}
	sizeBlock = append(sizeBlock, jen.Return(jen.Id("size")))

	f.Comment("SizeSSZ returns the total size of the serialized object")
	f.Func().Params(jen.Id("s").Op("*").Id(defName)).Id("SizeSSZ").Params().Int().Block(sizeBlock...)
	f.Line()

	// Generate getters and setters for each element
	for i := uint64(0); i < vectorSize; i++ {
		offsetPosition := uint64(i * 4)
		fieldName := fmt.Sprintf("element%d", i)

		// Getter
		f.Comment(fmt.Sprintf("Get%d returns element %d of the vector", i, i))
		f.Func().Params(jen.Id("s").Op("*").Id(defName)).Id(fmt.Sprintf("Get%d", i)).Params().Op("[]").Byte().Block(
			jen.Return(jen.Id("s").Dot(fieldName)),
		)
		f.Line()

		// Setter
		f.Comment(fmt.Sprintf("Set%d sets element %d of the vector", i, i))
		f.Func().Params(jen.Id("s").Op("*").Id(defName)).Id(fmt.Sprintf("Set%d", i)).Params(
			jen.Id("v").Op("[]").Byte(),
		).Block(
			jen.Id("s").Dot(fieldName).Op("=").Id("v"),
			jen.Comment(fmt.Sprintf("TODO: Update offset at position %d in fixedChunk", offsetPosition)),
		)
		f.Line()
	}

	return nil
}

// generateVariableContainer generates code for a variable-size container
func generateVariableContainer(f *jen.File, defName string, def cuessz.Def, ctx *GeneratorContext) error {
	// Check if we need to import solidssz for bitlists
	hasBitlist := false
	for _, child := range def.Children {
		if child.Def.Type == cuessz.TypeBitList {
			hasBitlist = true
			break
		}
	}
	if hasBitlist {
		f.ImportName("github.com/gfx-labs/ssz/pkg/solidssz", "solidssz")
	}

	// Separate fixed and variable fields
	var fixedFields []cuessz.Field
	var variableFields []cuessz.Field

	for _, child := range def.Children {
		if isFixedSize(child.Def, ctx) {
			fixedFields = append(fixedFields, child)
		} else {
			variableFields = append(variableFields, child)
		}
	}

	// Calculate fixed portion size and offsets
	fixedFieldOffsets := make([]uint64, len(fixedFields))
	currentOffset := uint64(0)

	for i, field := range fixedFields {
		fixedFieldOffsets[i] = currentOffset
		size, err := calculateFieldSize(field.Def, ctx)
		if err != nil {
			return fmt.Errorf("failed to calculate size of fixed field %s: %w", field.Name, err)
		}
		currentOffset += size
	}

	fixedFieldsSize := currentOffset
	offsetsStartPos := currentOffset
	// Add 4 bytes per variable field for offsets
	fixedSize := fixedFieldsSize + uint64(len(variableFields) * 4)

	// Generate detailed type comment with byte layout
	f.Comment(fmt.Sprintf("%s is a variable-size SSZ container", defName))
	f.Comment("")
	f.Comment("Byte layout of fixed chunk:")

	// Document fixed fields
	for i, field := range fixedFields {
		offset := fixedFieldOffsets[i]
		size, _ := calculateFieldSize(field.Def, ctx)
		endOffset := offset + size - 1
		typeDesc := getTypeDescription(field.Def)

		if offset == endOffset {
			f.Comment(fmt.Sprintf("[%3d]      %s (%s)", offset, field.Name, typeDesc))
		} else {
			f.Comment(fmt.Sprintf("[%3d-%3d]  %s (%s)", offset, endOffset, field.Name, typeDesc))
		}
	}

	// Document offsets for variable fields
	for i, field := range variableFields {
		offset := offsetsStartPos + uint64(i*4)
		endOffset := offset + 3
		f.Comment(fmt.Sprintf("[%3d-%3d]  offset for %s", offset, endOffset, field.Name))
	}

	f.Comment(fmt.Sprintf("Total fixed chunk size: %d bytes", fixedSize))
	f.Comment("")
	f.Comment("Variable fields stored separately:")
	for _, field := range variableFields {
		f.Comment(fmt.Sprintf("- %s: variable size", field.Name))
	}
	f.Line()

	// Generate struct definition with private fields
	structFields := []jen.Code{
		jen.Id("fixedChunk").Op("[]").Byte().Comment(fmt.Sprintf("Fixed fields + %d offsets", len(variableFields))),
	}

	for _, field := range variableFields {
		fieldName := toPrivateFieldName(field.Name) + "Data"
		structFields = append(structFields, jen.Id(fieldName).Op("[]").Byte())
	}

	f.Type().Id(defName).Struct(structFields...)
	f.Line()

	// Generate constructor
	f.Comment(fmt.Sprintf("New%s creates a new %s", defName, defName))
	constructorBlock := []jen.Code{
		jen.Id("s").Op(":=").Op("&").Id(defName).Values(
			jen.Id("fixedChunk").Op(":").Make(jen.Op("[]").Byte(), jen.Lit(int(fixedSize))),
		),
	}

	// Initialize offsets for variable fields
	if len(variableFields) > 0 {
		constructorBlock = append(constructorBlock, jen.Line())
		constructorBlock = append(constructorBlock, jen.Comment("Initialize offsets - all point to end of fixed chunk since fields start empty"))

		initialOffset := fixedSize // All offsets initially point to the end of fixed chunk
		for i := range variableFields {
			offsetPos := fixedFieldsSize + uint64(i*4)
			constructorBlock = append(constructorBlock,
				jen.Qual("encoding/binary", "LittleEndian").Dot("PutUint32").Call(
					jen.Id("s").Dot("fixedChunk").Index(jen.Lit(int(offsetPos)).Op(":").Lit(int(offsetPos+4))),
					jen.Uint32().Call(jen.Lit(int(initialOffset))),
				),
			)
		}
	}

	constructorBlock = append(constructorBlock, jen.Return(jen.Id("s")))

	f.Func().Id(fmt.Sprintf("New%s", defName)).Params().Op("*").Id(defName).Block(constructorBlock...)
	f.Line()

	// Generate NewFromSSZ constructor for deserialization
	f.Comment(fmt.Sprintf("New%sFromSSZ creates a %s from SSZ-encoded bytes", defName, defName))
	newFromSSZBlock := []jen.Code{
		jen.If(jen.Len(jen.Id("data")).Op("<").Lit(int(fixedSize))).Block(
			jen.Comment("Invalid data: too small for fixed chunk"),
			jen.Return(jen.Nil()),
		),
		jen.Line(),
		jen.Id("s").Op(":=").Op("&").Id(defName).Values(
			jen.Id("fixedChunk").Op(":").Make(jen.Op("[]").Byte(), jen.Lit(int(fixedSize))),
		),
		jen.Copy(jen.Id("s").Dot("fixedChunk"), jen.Id("data").Index(jen.Op(":").Lit(int(fixedSize)))),
	}

	if len(variableFields) > 0 {
		newFromSSZBlock = append(newFromSSZBlock, jen.Line())
		newFromSSZBlock = append(newFromSSZBlock, jen.Comment("Parse variable fields"))
		newFromSSZBlock = append(newFromSSZBlock, jen.Comment("First variable field always starts at fixedSize (which already includes all offsets)"))

		// First variable field starts right after the fixed chunk
		firstVariableOffset := fixedSize
		newFromSSZBlock = append(newFromSSZBlock,
			jen.Id("firstOffset").Op(":=").Uint32().Call(jen.Lit(int(firstVariableOffset))),
		)

		for i, field := range variableFields {
			fieldName := toPrivateFieldName(field.Name) + "Data"

			if i == 0 {
				// First field - we already know the offset
				if len(variableFields) > 1 {
					// Read next offset to find end
					nextOffsetPos := fixedFieldsSize + 4
					newFromSSZBlock = append(newFromSSZBlock,
						jen.Id("offset1").Op(":=").Qual("encoding/binary", "LittleEndian").Dot("Uint32").Call(
							jen.Id("s").Dot("fixedChunk").Index(jen.Lit(int(nextOffsetPos)).Op(":").Lit(int(nextOffsetPos+4))),
						),
						jen.Id("s").Dot(fieldName).Op("=").Id("data").Index(
							jen.Id("firstOffset").Op(":").Id("offset1"),
						),
					)
				} else {
					// Only one variable field - extends to end
					newFromSSZBlock = append(newFromSSZBlock,
						jen.Id("s").Dot(fieldName).Op("=").Id("data").Index(
							jen.Id("firstOffset").Op(":"),
						),
					)
				}
			} else if i < len(variableFields)-1 {
				// Middle fields - need to read current and next offset
				offsetPos := fixedFieldsSize + uint64(i*4)
				nextOffsetPos := offsetPos + 4
				newFromSSZBlock = append(newFromSSZBlock,
					jen.Id(fmt.Sprintf("offset%d", i)).Op(":=").Qual("encoding/binary", "LittleEndian").Dot("Uint32").Call(
						jen.Id("s").Dot("fixedChunk").Index(jen.Lit(int(offsetPos)).Op(":").Lit(int(offsetPos+4))),
					),
					jen.Id(fmt.Sprintf("offset%d", i+1)).Op(":=").Qual("encoding/binary", "LittleEndian").Dot("Uint32").Call(
						jen.Id("s").Dot("fixedChunk").Index(jen.Lit(int(nextOffsetPos)).Op(":").Lit(int(nextOffsetPos+4))),
					),
					jen.Id("s").Dot(fieldName).Op("=").Id("data").Index(
						jen.Id(fmt.Sprintf("offset%d", i)).Op(":").Id(fmt.Sprintf("offset%d", i+1)),
					),
				)
			} else {
				// Last field - read current offset, extends to end
				offsetPos := fixedFieldsSize + uint64(i*4)
				newFromSSZBlock = append(newFromSSZBlock,
					jen.Id(fmt.Sprintf("offset%d", i)).Op(":=").Qual("encoding/binary", "LittleEndian").Dot("Uint32").Call(
						jen.Id("s").Dot("fixedChunk").Index(jen.Lit(int(offsetPos)).Op(":").Lit(int(offsetPos+4))),
					),
					jen.Id("s").Dot(fieldName).Op("=").Id("data").Index(
						jen.Id(fmt.Sprintf("offset%d", i)).Op(":"),
					),
				)
			}
		}
	}

	newFromSSZBlock = append(newFromSSZBlock, jen.Line(), jen.Return(jen.Id("s")))

	f.Func().Id(fmt.Sprintf("New%sFromSSZ", defName)).Params(jen.Id("data").Op("[]").Byte()).Op("*").Id(defName).Block(newFromSSZBlock...)
	f.Line()

	// Fixed() method
	f.Comment("Fixed returns false as this is a variable-size container")
	f.Func().Params(jen.Id("s").Op("*").Id(defName)).Id("Fixed").Params().Bool().Block(
		jen.Return(jen.False()),
	)
	f.Line()

	// SizeSSZ() method - calculates dynamically for variable containers
	sizeBlock := []jen.Code{
		jen.Id("size").Op(":=").Len(jen.Id("s").Dot("fixedChunk")),
	}
	for _, field := range variableFields {
		fieldName := toPrivateFieldName(field.Name) + "Data"
		sizeBlock = append(sizeBlock,
			jen.Id("size").Op("+=").Len(jen.Id("s").Dot(fieldName)),
		)
	}
	sizeBlock = append(sizeBlock, jen.Return(jen.Id("size")))

	f.Func().Params(jen.Id("s").Op("*").Id(defName)).Id("SizeSSZ").Params().Int().Block(sizeBlock...)
	f.Line()

	// Generate getters and setters for fixed fields
	currentOffset = uint64(0)
	for _, field := range fixedFields {
		size, _ := calculateFieldSize(field.Def, ctx)
		generateVariableContainerFixedGetter(f, defName, field, currentOffset, size, ctx)
		generateVariableContainerFixedSetter(f, defName, field, currentOffset, size, ctx)
		currentOffset += size
	}

	// Generate getters and setters for variable fields
	for i, field := range variableFields {
		offsetPosition := currentOffset + uint64(i*4)
		generateVariableContainerVariableGetter(f, defName, field, offsetPosition, i, ctx)
		generateVariableContainerVariableSetter(f, defName, field, offsetPosition, i, ctx)
	}

	// Generate MarshalSSZ() method
	generateVariableContainerMarshalSSZ(f, defName, variableFields, fixedFieldsSize, fixedSize, ctx)

	return nil
}

// generateList generates code for a list type
func generateList(f *jen.File, defName string, def cuessz.Def, ctx *GeneratorContext) error {
	// Check the type of list
	if def.Type == cuessz.TypeBitList {
		return generateBitList(f, defName, def, ctx)
	}

	// Handle regular lists
	if len(def.Children) == 0 {
		return fmt.Errorf("list missing element type")
	}

	elemDef := def.Children[0].Def

	// Check if it's a byte list
	if elemDef.Type == cuessz.TypeUint8 {
		return generateByteList(f, defName, def, ctx)
	}

	// Check if element is fixed size
	if isFixedSize(elemDef, ctx) {
		return generateFixedElementList(f, defName, def, elemDef, ctx)
	}

	// Variable element list
	return generateVariableElementList(f, defName, def, elemDef, ctx)
}

// generateBitList generates code for a BitList type
func generateBitList(f *jen.File, defName string, def cuessz.Def, ctx *GeneratorContext) error {
	// Add import for solidssz package if we're using bitlists
	f.ImportName("github.com/gfx-labs/ssz/pkg/solidssz", "solidssz")

	// For standalone bitlists, just generate constructor functions
	f.Comment(fmt.Sprintf("%s is a BitList with maximum %d bits", defName, def.Limit))
	f.Comment(fmt.Sprintf("We use solidssz.Bitlist directly for this type"))
	f.Line()

	// Constructor function
	f.Comment(fmt.Sprintf("New%s creates a new bitlist with limit %d", defName, def.Limit))
	f.Func().Id(fmt.Sprintf("New%s", defName)).Params().Op("*").Qual("github.com/gfx-labs/ssz/pkg/solidssz", "Bitlist").Block(
		jen.Return(jen.Qual("github.com/gfx-labs/ssz/pkg/solidssz", "NewBitlist").Call(jen.Lit(def.Limit))),
	)
	f.Line()

	// NewFromSSZ constructor
	f.Comment(fmt.Sprintf("New%sFromSSZ creates a bitlist from SSZ-encoded bytes", defName))
	f.Func().Id(fmt.Sprintf("New%sFromSSZ", defName)).Params(jen.Id("data").Op("[]").Byte()).Params(jen.Op("*").Qual("github.com/gfx-labs/ssz/pkg/solidssz", "Bitlist"), jen.Error()).Block(
		jen.Return(jen.Qual("github.com/gfx-labs/ssz/pkg/solidssz", "NewBitlistFromSSZ").Call(
			jen.Id("data"), jen.Lit(def.Limit),
		)),
	)
	f.Line()

	return nil
}

// generateByteList generates code for a List[byte, N] type
func generateByteList(f *jen.File, defName string, def cuessz.Def, ctx *GeneratorContext) error {
	f.Comment(fmt.Sprintf("%s is a List[byte, %d]", defName, def.Limit))
	f.Type().Id(defName).Op("[]").Byte()
	f.Line()

	// Constructor
	f.Comment(fmt.Sprintf("New%s creates a new %s", defName, defName))
	f.Func().Id(fmt.Sprintf("New%s", defName)).Params().Id(defName).Block(
		jen.Return(jen.Make(jen.Op("[]").Byte(), jen.Lit(0))),
	)
	f.Line()

	// Fixed() method
	f.Func().Params(jen.Id("s").Id(defName)).Id("Fixed").Params().Bool().Block(
		jen.Return(jen.False()),
	)
	f.Line()

	// SizeSSZ() method - dynamic for byte lists
	f.Func().Params(jen.Id("s").Id(defName)).Id("SizeSSZ").Params().Int().Block(
		jen.Return(jen.Len(jen.Id("s"))),
	)
	f.Line()

	// MaxSize() method
	f.Func().Params(jen.Id("s").Id(defName)).Id("MaxSize").Params().Uint64().Block(
		jen.Return(jen.Lit(def.Limit)),
	)
	f.Line()

	return nil
}

// generateFixedElementList generates code for a List[FixedType, N]
func generateFixedElementList(f *jen.File, defName string, def cuessz.Def, elemDef cuessz.Def, ctx *GeneratorContext) error {
	elemSize, err := calculateFieldSize(elemDef, ctx)
	if err != nil {
		return fmt.Errorf("failed to calculate element size: %w", err)
	}

	// Get clean element type name for documentation
	elemTypeName := getElementTypeName(elemDef, ctx)

	f.Comment(fmt.Sprintf("%s is a List[%s, %d] with fixed element size %d", defName, elemTypeName, def.Limit, elemSize))
	f.Type().Id(defName).Op("[]").Byte()
	f.Line()

	// Constructor
	f.Comment(fmt.Sprintf("New%s creates a new %s", defName, defName))
	f.Func().Id(fmt.Sprintf("New%s", defName)).Params().Id(defName).Block(
		jen.Return(jen.Make(jen.Op("[]").Byte(), jen.Lit(0))),
	)
	f.Line()

	// Fixed() method
	f.Func().Params(jen.Id("s").Id(defName)).Id("Fixed").Params().Bool().Block(
		jen.Return(jen.False()),
	)
	f.Line()

	// SizeSSZ() method - dynamic for lists
	f.Func().Params(jen.Id("s").Id(defName)).Id("SizeSSZ").Params().Int().Block(
		jen.Return(jen.Len(jen.Id("s"))),
	)
	f.Line()

	// MaxSize() method
	f.Func().Params(jen.Id("s").Id(defName)).Id("MaxSize").Params().Uint64().Block(
		jen.Return(jen.Lit(def.Limit)),
	)
	f.Line()

	// ElementSize() method for fixed-size elements
	f.Func().Params(jen.Id("s").Id(defName)).Id("ElementSize").Params().Uint64().Block(
		jen.Return(jen.Lit(elemSize)),
	)
	f.Line()

	// Length() method
	f.Func().Params(jen.Id("s").Id(defName)).Id("Length").Params().Int().Block(
		jen.Return(jen.Len(jen.Id("s")).Op("/").Int().Call(jen.Id("s").Dot("ElementSize").Call())),
	)
	f.Line()

	// Get(index) method - returns element at index
	f.Func().Params(jen.Id("s").Id(defName)).Id("Get").Params(jen.Id("index").Int()).Op("[]").Byte().Block(
		jen.Id("elemSize").Op(":=").Id("s").Dot("ElementSize").Call(),
		jen.Id("start").Op(":=").Uint64().Call(jen.Id("index")).Op("*").Id("elemSize"),
		jen.Id("end").Op(":=").Id("start").Op("+").Id("elemSize"),
		jen.Return(jen.Id("s").Index(jen.Id("start").Op(":").Id("end"))),
	)
	f.Line()

	return nil
}

// generateVariableElementList generates code for a List[VariableType, N]
func generateVariableElementList(f *jen.File, defName string, def cuessz.Def, elemDef cuessz.Def, ctx *GeneratorContext) error {
	// Get clean element type name for documentation
	elemTypeName := getElementTypeName(elemDef, ctx)

	// Generate detailed documentation
	f.Comment(fmt.Sprintf("%s is a List[%s, %d] with variable-size elements", defName, elemTypeName, def.Limit))
	f.Comment("")
	f.Comment("SSZ encoding:")
	f.Comment("- First N*4 bytes: offsets (uint32) pointing to each element's start position")
	f.Comment("- Remaining bytes: concatenated element data")
	f.Comment("")
	f.Comment("The offsets are relative to the beginning of the list data.")
	f.Comment(fmt.Sprintf("Maximum %d elements allowed.", def.Limit))
	f.Line()

	// Generate type as []byte alias
	f.Type().Id(defName).Op("[]").Byte()
	f.Line()

	// Constructor
	f.Comment(fmt.Sprintf("New%s creates a new empty %s", defName, defName))
	f.Func().Id(fmt.Sprintf("New%s", defName)).Params().Id(defName).Block(
		jen.Comment("Start with empty list (no offsets, no data)"),
		jen.Return(jen.Make(jen.Op("[]").Byte(), jen.Lit(0))),
	)
	f.Line()

	// Fixed() method
	f.Comment("Fixed returns false as this is a variable-size list")
	f.Func().Params(jen.Id("l").Id(defName)).Id("Fixed").Params().Bool().Block(
		jen.Return(jen.False()),
	)
	f.Line()

	// SizeSSZ() method
	f.Comment("SizeSSZ returns the total size of the serialized list")
	f.Func().Params(jen.Id("l").Id(defName)).Id("SizeSSZ").Params().Int().Block(
		jen.Return(jen.Len(jen.Id("l"))),
	)
	f.Line()

	// MaxElements() method
	f.Comment(fmt.Sprintf("MaxElements returns the maximum number of elements (%d)", def.Limit))
	f.Func().Params(jen.Id("l").Id(defName)).Id("MaxElements").Params().Uint64().Block(
		jen.Return(jen.Lit(def.Limit)),
	)
	f.Line()

	// Length() method
	f.Comment("Length returns the number of elements in the list")
	f.Func().Params(jen.Id("l").Id(defName)).Id("Length").Params().Int().Block(
		jen.If(jen.Len(jen.Id("l")).Op("==").Lit(0)).Block(
			jen.Return(jen.Lit(0)),
		),
		jen.Comment("Number of elements = total size / 4 before we reach the first offset value"),
		jen.Comment("Read first offset to determine where data starts"),
		jen.If(jen.Len(jen.Id("l")).Op("<").Lit(4)).Block(
			jen.Return(jen.Lit(0)), jen.Comment("Invalid list"),
		),
		jen.Id("firstOffset").Op(":=").Qual("encoding/binary", "LittleEndian").Dot("Uint32").Call(jen.Id("l").Index(jen.Lit(0).Op(":").Lit(4))),
		jen.Comment("Number of offsets = first offset / 4"),
		jen.Return(jen.Int().Call(jen.Id("firstOffset")).Op("/").Lit(4)),
	)
	f.Line()

	// Get the actual element type name
	elementTypeName := elemTypeName
	if elemDef.Type == cuessz.TypeRef {
		elementTypeName = elemDef.Ref
	}

	// Get(index) method
	f.Comment("Get returns the element at the given index")
	f.Func().Params(jen.Id("l").Id(defName)).Id("Get").Params(jen.Id("index").Int()).Params(jen.Id(elementTypeName), jen.Error()).Block(
		jen.Id("length").Op(":=").Id("l").Dot("Length").Call(),
		jen.If(jen.Id("index").Op("<").Lit(0).Op("||").Id("index").Op(">=").Id("length")).Block(
			jen.Return(jen.Nil(), jen.Qual("fmt", "Errorf").Call(jen.Lit("index %d out of bounds [0, %d)"), jen.Id("index"), jen.Id("length"))),
		),
		jen.Line(),
		jen.Comment("Calculate element boundaries"),
		jen.Comment("Note: First element always starts at length * 4 (after all offsets)"),
		jen.Var().Id("elementOffset").Uint32(),
		jen.If(jen.Id("index").Op("==").Lit(0)).Block(
			jen.Comment("First element starts after all offsets"),
			jen.Id("elementOffset").Op("=").Uint32().Call(jen.Id("length").Op("*").Lit(4)),
		).Else().Block(
			jen.Comment("Read offset for non-first elements"),
			jen.Id("offsetPos").Op(":=").Id("index").Op("*").Lit(4),
			jen.Id("elementOffset").Op("=").Qual("encoding/binary", "LittleEndian").Dot("Uint32").Call(
				jen.Id("l").Index(jen.Id("offsetPos").Op(":").Id("offsetPos").Op("+").Lit(4)),
			),
		),
		jen.Line(),
		jen.Comment("Determine the end of this element"),
		jen.Var().Id("elementEnd").Uint32(),
		jen.If(jen.Id("index").Op("==").Id("length").Op("-").Lit(1)).Block(
			jen.Comment("Last element extends to end of data"),
			jen.Id("elementEnd").Op("=").Uint32().Call(jen.Len(jen.Id("l"))),
		).Else().Block(
			jen.Comment("Read next offset to find end"),
			jen.Id("nextOffsetPos").Op(":=").Parens(jen.Id("index").Op("+").Lit(1)).Op("*").Lit(4),
			jen.Id("elementEnd").Op("=").Qual("encoding/binary", "LittleEndian").Dot("Uint32").Call(
				jen.Id("l").Index(jen.Id("nextOffsetPos").Op(":").Id("nextOffsetPos").Op("+").Lit(4)),
			),
		),
		jen.Line(),
		jen.Comment("Extract element data"),
		jen.Id("elementData").Op(":=").Id("l").Index(jen.Id("elementOffset").Op(":").Id("elementEnd")),
		jen.Line(),
		jen.Comment("Create new element from SSZ bytes"),
		jen.Id("element").Op(":=").Id(fmt.Sprintf("New%sFromSSZ", elementTypeName)).Call(jen.Id("elementData")),
		jen.Return(jen.Id("element"), jen.Nil()),
	)
	f.Line()

	// Append method
	f.Comment("Append adds a new element to the list")
	f.Func().Params(jen.Id("l").Op("*").Id(defName)).Id("Append").Params(jen.Id("element").Id(elementTypeName)).Error().Block(
		jen.Id("currentLength").Op(":=").Parens(jen.Op("*").Id("l")).Dot("Length").Call(),
		jen.If(jen.Uint64().Call(jen.Id("currentLength")).Op(">=").Parens(jen.Op("*").Id("l")).Dot("MaxElements").Call()).Block(
			jen.Return(jen.Qual("fmt", "Errorf").Call(jen.Lit("list is at maximum capacity (%d elements)"), jen.Parens(jen.Op("*").Id("l")).Dot("MaxElements").Call())),
		),
		jen.Line(),
		jen.Comment("Convert element to bytes"),
		jen.Id("elementBytes").Op(":=").Op("[]").Byte().Call(jen.Id("element")),
		jen.Line(),
		jen.Comment("Calculate new offsets"),
		jen.Id("newOffsetCount").Op(":=").Id("currentLength").Op("+").Lit(1),
		jen.Id("offsetsSize").Op(":=").Id("newOffsetCount").Op("*").Lit(4),
		jen.Line(),
		jen.Comment("Calculate where the new element will start"),
		jen.Var().Id("newElementOffset").Uint32(),
		jen.If(jen.Id("currentLength").Op("==").Lit(0)).Block(
			jen.Comment("First element starts right after offsets"),
			jen.Id("newElementOffset").Op("=").Uint32().Call(jen.Id("offsetsSize")),
		).Else().Block(
			jen.Comment("New element starts at current end of data"),
			jen.Id("newElementOffset").Op("=").Uint32().Call(jen.Len(jen.Op("*").Id("l"))),
		),
		jen.Line(),
		jen.Comment("Create new buffer with space for new offset and element"),
		jen.Id("newSize").Op(":=").Id("offsetsSize").Op("+").Int().Call(jen.Id("newElementOffset").Op("-").Uint32().Call(jen.Id("offsetsSize"))).Op("+").Len(jen.Id("elementBytes")),
		jen.Id("newData").Op(":=").Make(jen.Op("[]").Byte(), jen.Id("newSize")),
		jen.Line(),
		jen.Comment("Copy existing offsets and update them if needed"),
		jen.If(jen.Id("currentLength").Op(">").Lit(0)).Block(
			jen.Comment("Copy existing offsets"),
			jen.Copy(jen.Id("newData"), jen.Parens(jen.Op("*").Id("l")).Index(jen.Lit(0).Op(":").Id("currentLength").Op("*").Lit(4))),
			jen.Comment("Copy existing data"),
			jen.Id("existingDataStart").Op(":=").Id("currentLength").Op("*").Lit(4),
			jen.Copy(jen.Id("newData").Index(jen.Id("offsetsSize").Op(":")), jen.Parens(jen.Op("*").Id("l")).Index(jen.Id("existingDataStart").Op(":"))),
		),
		jen.Line(),
		jen.Comment("Add new offset"),
		jen.Qual("encoding/binary", "LittleEndian").Dot("PutUint32").Call(
			jen.Id("newData").Index(jen.Id("currentLength").Op("*").Lit(4).Op(":").Id("offsetsSize")),
			jen.Id("newElementOffset"),
		),
		jen.Line(),
		jen.Comment("Add new element data"),
		jen.Copy(jen.Id("newData").Index(jen.Id("newElementOffset").Op(":")), jen.Id("elementBytes")),
		jen.Line(),
		jen.Op("*").Id("l").Op("=").Id(defName).Call(jen.Id("newData")),
		jen.Return(jen.Nil()),
	)
	f.Line()

	// Clear method
	f.Comment("Clear removes all elements from the list")
	f.Func().Params(jen.Id("l").Op("*").Id(defName)).Id("Clear").Params().Block(
		jen.Op("*").Id("l").Op("=").Make(jen.Op("[]").Byte(), jen.Lit(0)),
	)
	f.Line()

	return nil
}

// Helper functions for variable containers
func generateVariableContainerFixedGetter(f *jen.File, typeName string, field cuessz.Field, offset, size uint64, ctx *GeneratorContext) {
	methodName := snakeToCamel(field.Name)
	def := field.Def

	// Resolve refs
	if def.Type == cuessz.TypeRef {
		if refDef, ok := ctx.Defs[def.Ref]; ok {
			def = refDef
		}
	}

	var returnType *jen.Statement
	var body *jen.Statement

	switch def.Type {
	case cuessz.TypeBoolean:
		returnType = jen.Bool()
		body = jen.Return(jen.Id("s").Dot("fixedChunk").Index(jen.Lit(int(offset))).Op("!=").Lit(0))
	case cuessz.TypeUint8:
		returnType = jen.Uint8()
		body = jen.Return(jen.Id("s").Dot("fixedChunk").Index(jen.Lit(int(offset))))
	case cuessz.TypeUint16:
		returnType = jen.Uint16()
		body = jen.Return(jen.Qual("encoding/binary", "LittleEndian").Dot("Uint16").Call(
			jen.Id("s").Dot("fixedChunk").Index(jen.Lit(int(offset)).Op(":").Lit(int(offset+size))),
		))
	case cuessz.TypeUint32:
		returnType = jen.Uint32()
		body = jen.Return(jen.Qual("encoding/binary", "LittleEndian").Dot("Uint32").Call(
			jen.Id("s").Dot("fixedChunk").Index(jen.Lit(int(offset)).Op(":").Lit(int(offset+size))),
		))
	case cuessz.TypeUint64:
		returnType = jen.Uint64()
		body = jen.Return(jen.Qual("encoding/binary", "LittleEndian").Dot("Uint64").Call(
			jen.Id("s").Dot("fixedChunk").Index(jen.Lit(int(offset)).Op(":").Lit(int(offset+size))),
		))
	default:
		returnType = jen.Op("[]").Byte()
		body = jen.Return(jen.Id("s").Dot("fixedChunk").Index(jen.Lit(int(offset)).Op(":").Lit(int(offset+size))))
	}

	// Add documentation
	comment := fmt.Sprintf("%s returns the %s field", methodName, field.Name)
	if field.Description != nil && *field.Description != "" {
		comment = fmt.Sprintf("%s returns the %s field (%s)", methodName, field.Name, *field.Description)
	}
	f.Comment(comment)
	f.Func().Params(jen.Id("s").Op("*").Id(typeName)).Id(methodName).Params().Add(returnType).Block(body)
	f.Line()
}

