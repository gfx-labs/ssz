func generateVariableContainerVariableGetter(f *jen.File, typeName string, field cuessz.Field, offsetPosition uint64, index int, ctx *GeneratorContext) {
	methodName := snakeToCamel(field.Name)
	fieldName := toPrivateFieldName(field.Name) + "Data"

	// Check if this is a bitlist
	var returnType *jen.Statement
	isListType := false
	isBitlist := false

	if field.Def.Type == cuessz.TypeBitList {
		// For bitlists, we return solidssz.Bitlist directly
		returnType = jen.Op("*").Qual("github.com/gfx-labs/ssz/pkg/solidssz", "Bitlist")
		isBitlist = true
	} else if field.Def.Type == cuessz.TypeList && len(field.Def.Children) > 0 {
		elemDef := field.Def.Children[0].Def
		if !isFixedSize(elemDef, ctx) {
			// This is a list of variable-size elements, use the generated list type
			listTypeName := snakeToCamel(field.Name) + "List"
			if elemDef.Type == cuessz.TypeRef && elemDef.Ref != "" {
				listTypeName = elemDef.Ref + "List"
			}
			returnType = jen.Id(listTypeName)
			isListType = true
		}
	}

	if returnType == nil {
		returnType = jen.Op("[]").Byte()
	}

	// Add documentation
	comment := fmt.Sprintf("%s returns the %s field (variable-size)", methodName, field.Name)
	if field.Description != nil && *field.Description != "" {
		comment = fmt.Sprintf("%s returns the %s field - %s (variable-size)", methodName, field.Name, *field.Description)
	}
	f.Comment(comment)

	if isBitlist {
		// For bitlists, we need to deserialize from the stored bytes
		f.Func().Params(jen.Id("s").Op("*").Id(typeName)).Id(methodName).Params().Params(returnType, jen.Error()).Block(
			jen.Return(jen.Qual("github.com/gfx-labs/ssz/pkg/solidssz", "NewBitlistFromSSZ").Call(
				jen.Id("s").Dot(fieldName),
				jen.Lit(field.Def.Limit),
			)),
		)
	} else if isListType {
		f.Func().Params(jen.Id("s").Op("*").Id(typeName)).Id(methodName).Params().Add(returnType).Block(
			jen.Return(returnType.Clone().Call(jen.Id("s").Dot(fieldName))),
		)
	} else {
		f.Func().Params(jen.Id("s").Op("*").Id(typeName)).Id(methodName).Params().Add(returnType).Block(
			jen.Return(jen.Id("s").Dot(fieldName)),
		)
	}
	f.Line()
}

