func generateVariableContainerMarshalSSZ(f *jen.File, typeName string, variableFields []cuessz.Field, fixedFieldsSize, fixedSize uint64, ctx *GeneratorContext) {
	// MarshalSSZ() method
	f.Comment("MarshalSSZ serializes the container to SSZ format")

	marshalBlock := []jen.Code{
		jen.Comment("Create a copy of fixedChunk to avoid modifying the original"),
		jen.Id("fixedChunkCopy").Op(":=").Make(jen.Op("[]").Byte(), jen.Len(jen.Id("s").Dot("fixedChunk"))),
		jen.Copy(jen.Id("fixedChunkCopy"), jen.Id("s").Dot("fixedChunk")),
		jen.Line(),
	}

	if len(variableFields) > 0 {
		marshalBlock = append(marshalBlock, jen.Comment("Calculate and write offsets for variable fields"))

		// Calculate each offset
		for i := range variableFields {
			offsetPosition := fixedFieldsSize + uint64(i*4)

			if i == 0 {
				// First variable field always starts at fixedSize
				marshalBlock = append(marshalBlock,
					jen.Qual("encoding/binary", "LittleEndian").Dot("PutUint32").Call(
						jen.Id("fixedChunkCopy").Index(jen.Lit(int(offsetPosition)).Op(":").Lit(int(offsetPosition+4))),
						jen.Uint32().Call(jen.Lit(int(fixedSize))),
					),
				)
			} else {
				// Subsequent fields: offset = fixedSize + sum of all previous variable fields
				marshalBlock = append(marshalBlock, jen.Id(fmt.Sprintf("offset%d", i)).Op(":=").Uint32().Call(jen.Lit(int(fixedSize))))

				// Add sizes of all previous variable fields
				for j := 0; j < i; j++ {
					prevFieldName := toPrivateFieldName(variableFields[j].Name) + "Data"
					marshalBlock = append(marshalBlock,
						jen.Id(fmt.Sprintf("offset%d", i)).Op("+=").Uint32().Call(jen.Len(jen.Id("s").Dot(prevFieldName))),
					)
				}

				marshalBlock = append(marshalBlock,
					jen.Qual("encoding/binary", "LittleEndian").Dot("PutUint32").Call(
						jen.Id("fixedChunkCopy").Index(jen.Lit(int(offsetPosition)).Op(":").Lit(int(offsetPosition+4))),
						jen.Id(fmt.Sprintf("offset%d", i)),
					),
				)
			}
		}

		marshalBlock = append(marshalBlock, jen.Line())
		marshalBlock = append(marshalBlock, jen.Comment("Concatenate fixed chunk and variable fields"))
		marshalBlock = append(marshalBlock, jen.Id("result").Op(":=").Make(jen.Op("[]").Byte(), jen.Lit(0), jen.Id("s").Dot("SizeSSZ").Call()))
		marshalBlock = append(marshalBlock, jen.Id("result").Op("=").Id("append").Call(jen.Id("result"), jen.Id("fixedChunkCopy").Op("...")))

		for _, field := range variableFields {
			fieldName := toPrivateFieldName(field.Name) + "Data"
			marshalBlock = append(marshalBlock,
				jen.Id("result").Op("=").Id("append").Call(jen.Id("result"), jen.Id("s").Dot(fieldName).Op("...")),
			)
		}

		marshalBlock = append(marshalBlock, jen.Return(jen.Id("result"), jen.Nil()))
	} else {
		// No variable fields, just return the fixed chunk
		marshalBlock = append(marshalBlock, jen.Return(jen.Id("fixedChunkCopy"), jen.Nil()))
	}

	f.Func().Params(jen.Id("s").Op("*").Id(typeName)).Id("MarshalSSZ").Params().Params(jen.Op("[]").Byte(), jen.Error()).Block(marshalBlock...)
	f.Line()
}
