package gostructgen

import (
	"fmt"
	"strings"

	"github.com/dave/jennifer/jen"
	"github.com/gfx-labs/cuessz"
	"github.com/gfx-labs/ssz/pkg/dag"
)

// Config holds configuration options for code generation
type Config struct {
	// UsePointersForContainers controls whether container refs use pointers (*Type) or values (Type)
	// Default: true (use pointers for backward compatibility with existing SSZ libraries)
	UsePointersForContainers bool
}

// DefaultConfig returns the default configuration
func DefaultConfig() *Config {
	return &Config{
		UsePointersForContainers: true,
	}
}

// GenerateCode generates Go structs with SSZ annotations using default config
func GenerateCode(packageName string, defs map[string]cuessz.Def) (*jen.File, error) {
	return GenerateCodeWithConfig(packageName, defs, DefaultConfig())
}

// GenerateCodeWithConfig generates Go structs with SSZ annotations using custom config
func GenerateCodeWithConfig(packageName string, defs map[string]cuessz.Def, config *Config) (*jen.File, error) {
	f := jen.NewFile(packageName)

	// Add generated code comment
	f.HeaderComment("Code generated by genssz gostruct. DO NOT EDIT.")

	// Sort def names by dependency order (types with no deps first)
	// then alphabetically within each layer
	defNames := dag.TopologicalSort(defs)

	// Generate code for each def in sorted order
	for _, defName := range defNames {
		def := defs[defName]
		switch def.Type {
		case cuessz.TypeContainer, cuessz.TypeProgressiveContainer:
			// Generate struct definition
			err := generateStruct(f, defName, def, defs, config)
			if err != nil {
				return nil, fmt.Errorf("failed to generate %s: %w", defName, err)
			}
		case cuessz.TypeRef:
			// Generate type alias
			if def.Ref != "" {
				refDef, ok := defs[def.Ref]
				if !ok {
					return nil, fmt.Errorf("ref type '%s' not found", def.Ref)
				}
				aliasType, err := getDefType(refDef, defs, config)
				if err != nil {
					return nil, fmt.Errorf("failed to generate alias %s: %w", defName, err)
				}
				// Add description comment if available
				if def.Description != nil && *def.Description != "" {
					f.Comment(*def.Description)
				}
				// Add SSZ type information
				f.Comment(fmt.Sprintf("SSZ: alias of %s", def.Ref))
				f.Type().Id(defName).Add(aliasType)
				f.Line()
			}
		default:
			// For basic types, generate as type alias
			baseType, err := getDefType(def, defs, config)
			if err != nil {
				return nil, fmt.Errorf("failed to generate type %s: %w", defName, err)
			}
			// Add description comment if available
			if def.Description != nil && *def.Description != "" {
				f.Comment(*def.Description)
			}
			// Add SSZ type information
			sszInfo := buildSSZTypeCommentForBasicType(def)
			f.Comment(sszInfo)
			f.Type().Id(defName).Add(baseType)
			f.Line()
		}
	}

	return f, nil
}

// generateStruct generates a Go struct with SSZ annotations
func generateStruct(f *jen.File, defName string, def cuessz.Def, defs map[string]cuessz.Def, config *Config) error {
	// Add type description comment if available
	if def.Description != nil && *def.Description != "" {
		f.Comment(*def.Description)
	}

	// Add SSZ type information comment
	sszTypeInfo := buildSSZTypeComment(def)
	f.Comment(sszTypeInfo)

	// Build struct fields
	structFields := []jen.Code{}

	// For progressive containers, calculate ssz-index from active_fields
	var sszIndices []int
	if def.Type == cuessz.TypeProgressiveContainer && len(def.ActiveFields) > 0 {
		// Build mapping from child index to merkle tree index
		sszIndices = make([]int, len(def.Children))
		childIdx := 0
		for merkleIdx, active := range def.ActiveFields {
			if active == 1 {
				if childIdx < len(def.Children) {
					sszIndices[childIdx] = merkleIdx
					childIdx++
				}
			}
		}
	}

	for i, child := range def.Children {
		// Get field type
		fieldType, err := getFieldType(child, defs, config)
		if err != nil {
			return fmt.Errorf("failed to get type for field %s: %w", child.Name, err)
		}

		// Get struct tags as a map
		tags := getStructTagsWithParent(child, defs, &def)

		// Add ssz-index for progressive containers
		if len(sszIndices) > 0 && i < len(sszIndices) {
			tags["ssz-index"] = fmt.Sprintf("%d", sszIndices[i])
		}

		// Capitalize field name for export
		capitalName := capitalize(child.Name)

		// Build the field with tags and optional comment
		// Note: jennifer's Tag() method sorts tags alphabetically,
		// so we post-process to reorder them (JSON first, then SSZ tags)
		fieldDef := jen.Id(capitalName).Add(fieldType).Tag(tags)

		// Add field description comment if available
		if child.Description != nil && *child.Description != "" {
			fieldDef = fieldDef.Comment(*child.Description)
		}

		structFields = append(structFields, fieldDef)
	}

	// Generate the struct
	f.Type().Id(defName).Struct(structFields...)
	f.Line()

	return nil
}

// getFieldType returns the Go type for a cuessz field
func getFieldType(field cuessz.Field, defs map[string]cuessz.Def, config *Config) (*jen.Statement, error) {
	return getDefType(field.Def, defs, config)
}

// getDefType returns the Go type for a cuessz def
func getDefType(def cuessz.Def, defs map[string]cuessz.Def, config *Config) (*jen.Statement, error) {
	switch def.Type {
	case cuessz.TypeBoolean:
		return jen.Bool(), nil

	case cuessz.TypeUint8:
		return jen.Uint8(), nil

	case cuessz.TypeUint16:
		return jen.Uint16(), nil

	case cuessz.TypeUint32:
		return jen.Uint32(), nil

	case cuessz.TypeUint64:
		return jen.Uint64(), nil

	case cuessz.TypeUint128:
		// uint128 is represented as [16]byte
		return jen.Index(jen.Lit(16)).Byte(), nil

	case cuessz.TypeUint256:
		// uint256 is represented as [32]byte
		return jen.Index(jen.Lit(32)).Byte(), nil

	case cuessz.TypeBitVector:
		// BitVector is represented as fixed-size byte array
		size := (def.Size + 7) / 8
		return jen.Index(jen.Lit(int(size))).Byte(), nil

	case cuessz.TypeBitList:
		// BitList is represented as variable-size byte slice
		return jen.Op("[]").Byte(), nil

	case cuessz.TypeVector:
		// Fixed-size vector
		if len(def.Children) == 0 {
			return nil, fmt.Errorf("vector missing element type")
		}
		elemType, err := getFieldType(def.Children[0], defs, config)
		if err != nil {
			return nil, err
		}
		return jen.Index(jen.Lit(int(def.Size))).Add(elemType), nil

	case cuessz.TypeList:
		// Variable-size list
		if len(def.Children) == 0 {
			return nil, fmt.Errorf("list missing element type")
		}
		elemType, err := getFieldType(def.Children[0], defs, config)
		if err != nil {
			return nil, err
		}
		return jen.Op("[]").Add(elemType), nil

	case cuessz.TypeContainer, cuessz.TypeProgressiveContainer:
		// Nested container - we need to find the name from defs
		// For nested containers, we can't use the name directly because we don't have it
		// We'll use interface{} for now as a placeholder
		// This needs to be improved to handle nested named containers properly
		return jen.Interface(), nil

	case cuessz.TypeRef:
		// Reference to another type
		if def.Ref == "" {
			return nil, fmt.Errorf("def has type 'ref' but no ref specified")
		}
		refDef, ok := defs[def.Ref]
		if !ok {
			return nil, fmt.Errorf("ref type '%s' not found", def.Ref)
		}

		// If the ref is a container, optionally use pointer to the type
		if refDef.Type == cuessz.TypeContainer || refDef.Type == cuessz.TypeProgressiveContainer {
			if config.UsePointersForContainers {
				return jen.Op("*").Id(def.Ref), nil
			}
			return jen.Id(def.Ref), nil
		}

		// For other types (vectors, basic types), use the type name directly
		// This creates type aliases like Root, Signature, etc.
		return jen.Id(def.Ref), nil

	case cuessz.TypeUnion:
		// Unions are typically represented as interface{} or []byte
		return jen.Interface(), nil

	default:
		return nil, fmt.Errorf("unknown type: %s", def.Type)
	}
}

// getStructTags returns SSZ struct tags for a field
func getStructTags(field cuessz.Field, defs map[string]cuessz.Def) map[string]string {
	return getStructTagsWithParent(field, defs, nil)
}

// getStructTagsWithParent returns SSZ struct tags for a field, with access to parent def for progressive containers
func getStructTagsWithParent(field cuessz.Field, defs map[string]cuessz.Def, parentDef *cuessz.Def) map[string]string {
	tags := map[string]string{
		"json": toJSONName(field.Name),
	}

	def := field.Def

	switch def.Type {
	case cuessz.TypeVector:
		// Fixed-size vector needs ssz-size tag
		if len(def.Children) > 0 {
			// Check if it's a multidimensional array (vector of vectors/arrays)
			elemDef := def.Children[0].Def
			if elemDef.Type == cuessz.TypeVector && len(elemDef.Children) > 0 {
				// Multidimensional: [N][M]type
				tags["ssz-size"] = fmt.Sprintf("%d,%d", def.Size, elemDef.Size)
			} else {
				tags["ssz-size"] = fmt.Sprintf("%d", def.Size)
			}
		} else {
			tags["ssz-size"] = fmt.Sprintf("%d", def.Size)
		}

	case cuessz.TypeList:
		// Variable-size list needs ssz-max tag
		if len(def.Children) > 0 {
			elemDef := def.Children[0].Def
			// Check for nested lists ([][])
			if elemDef.Type == cuessz.TypeList {
				// Nested variable list: [][]byte with max sizes
				tags["ssz-max"] = fmt.Sprintf("%d,%d", def.Limit, elemDef.Limit)
				tags["ssz-size"] = "?,?"
			} else if elemDef.Type == cuessz.TypeVector {
				// List of fixed-size items: [][N]byte
				tags["ssz-max"] = fmt.Sprintf("%d", def.Limit)
				tags["ssz-size"] = fmt.Sprintf("?,%d", elemDef.Size)
			} else {
				tags["ssz-max"] = fmt.Sprintf("%d", def.Limit)
			}
		} else {
			tags["ssz-max"] = fmt.Sprintf("%d", def.Limit)
		}

	case cuessz.TypeBitVector:
		// BitVector needs ssz-size tag (in bits converted to bytes)
		byteSize := (def.Size + 7) / 8
		tags["ssz-size"] = fmt.Sprintf("%d", byteSize)

	case cuessz.TypeBitList:
		// BitList needs ssz:"bitlist" and ssz-max tag (in bits)
		tags["ssz"] = "bitlist"
		tags["ssz-max"] = fmt.Sprintf("%d", def.Limit)

	case cuessz.TypeProgressiveContainer:
		// ProgressiveContainer always has limit of 256
		tags["ssz-max"] = "256"

	case cuessz.TypeRef:
		// For refs, we need to get the SSZ tags from the referenced type
		// but keep the JSON tag from this field
		if def.Ref != "" {
			if refDef, ok := defs[def.Ref]; ok {
				// Create a temporary field for the ref to get its tags
				tempField := cuessz.Field{
					Name: field.Name, // Use original field name for JSON tag
					Def:  refDef,
				}
				// Get SSZ tags from the referenced type
				refTags := getStructTags(tempField, defs)
				// Override the JSON tag to use this field's name
				refTags["json"] = toJSONName(field.Name)
				return refTags
			}
		}
	}

	return tags
}

// buildSSZTypeComment creates a comment describing the SSZ type information
func buildSSZTypeComment(def cuessz.Def) string {
	switch def.Type {
	case cuessz.TypeContainer:
		return "SSZ: container"
	case cuessz.TypeProgressiveContainer:
		if len(def.ActiveFields) > 0 {
			// Format the bitset compactly (e.g., "1001" instead of "[1, 0, 0, 1]")
			var bitset strings.Builder
			for _, bit := range def.ActiveFields {
				bitset.WriteString(fmt.Sprintf("%d", bit))
			}
			return fmt.Sprintf("SSZ: progressive_container, active_fields: %s", bitset.String())
		}
		return "SSZ: progressive_container"
	default:
		return fmt.Sprintf("SSZ: %s", def.Type)
	}
}

// buildSSZTypeCommentForBasicType creates a comment for basic types like vectors, lists, etc.
func buildSSZTypeCommentForBasicType(def cuessz.Def) string {
	switch def.Type {
	case cuessz.TypeVector:
		elemType := "uint8"
		if len(def.Children) > 0 {
			elemType = string(def.Children[0].Def.Type)
		}
		return fmt.Sprintf("SSZ: vector[%d] of %s", def.Size, elemType)
	case cuessz.TypeList:
		elemType := "uint8"
		if len(def.Children) > 0 {
			elemType = string(def.Children[0].Def.Type)
		}
		return fmt.Sprintf("SSZ: list[max=%d] of %s", def.Limit, elemType)
	case cuessz.TypeBitVector:
		return fmt.Sprintf("SSZ: bitvector[%d]", def.Size)
	case cuessz.TypeBitList:
		return fmt.Sprintf("SSZ: bitlist[max=%d]", def.Limit)
	case cuessz.TypeBoolean:
		return "SSZ: bool"
	case cuessz.TypeUint8:
		return "SSZ: uint8"
	case cuessz.TypeUint16:
		return "SSZ: uint16"
	case cuessz.TypeUint32:
		return "SSZ: uint32"
	case cuessz.TypeUint64:
		return "SSZ: uint64"
	case cuessz.TypeUint128:
		return "SSZ: uint128"
	case cuessz.TypeUint256:
		return "SSZ: uint256"
	default:
		return fmt.Sprintf("SSZ: %s", def.Type)
	}
}

// capitalize converts snake_case or camelCase to PascalCase
func capitalize(s string) string {
	if len(s) == 0 {
		return s
	}

	// Split on underscores
	parts := strings.Split(s, "_")
	for i, part := range parts {
		if len(part) > 0 {
			parts[i] = strings.ToUpper(part[:1]) + part[1:]
		}
	}
	return strings.Join(parts, "")
}

// toJSONName converts a field name to JSON naming convention (snake_case)
func toJSONName(s string) string {
	// If already snake_case, return as-is
	if strings.Contains(s, "_") {
		return s
	}

	// Convert camelCase to snake_case
	var result strings.Builder
	for i, r := range s {
		if i > 0 && r >= 'A' && r <= 'Z' {
			result.WriteRune('_')
		}
		result.WriteRune(r)
	}

	return strings.ToLower(result.String())
}
