package pysszgen

import (
	"fmt"
	"sort"
	"strings"

	"github.com/gfx-labs/cuessz"
	"github.com/gfx-labs/ssz/pkg/dag"
)

// GenerateCode generates Python classes for py-ssz
func GenerateCode(defs map[string]cuessz.Def) (string, error) {
	var output strings.Builder

	// Generate header comment
	output.WriteString("# Code generated by genssz pyssz. DO NOT EDIT.\n\n")

	// Collect all required imports
	imports := collectImports(defs)

	// Generate imports
	if len(imports.containers) > 0 {
		output.WriteString("from ssz.hashable_container import (\n")
		containerImports := make([]string, 0, len(imports.containers))
		for imp := range imports.containers {
			containerImports = append(containerImports, imp)
		}
		sort.Strings(containerImports)
		for _, imp := range containerImports {
			output.WriteString(fmt.Sprintf("    %s,\n", imp))
		}
		output.WriteString(")\n")
	}

	if len(imports.sedes) > 0 {
		output.WriteString("from ssz.sedes import (\n")
		sedesImports := make([]string, 0, len(imports.sedes))
		for imp := range imports.sedes {
			sedesImports = append(sedesImports, imp)
		}
		sort.Strings(sedesImports)
		for _, imp := range sedesImports {
			output.WriteString(fmt.Sprintf("    %s,\n", imp))
		}
		output.WriteString(")\n")
	}

	output.WriteString("\n\n")

	// Sort def names by dependency order
	defNames := dag.TopologicalSort(defs)

	// Generate code for each def in sorted order
	for _, defName := range defNames {
		def := defs[defName]
		switch def.Type {
		case cuessz.TypeContainer, cuessz.TypeProgressiveContainer:
			// Generate class definition
			err := generateClass(&output, defName, def, defs)
			if err != nil {
				return "", fmt.Errorf("failed to generate %s: %w", defName, err)
			}
		case cuessz.TypeRef:
			// Generate type alias
			if def.Ref != "" {
				refDef, ok := defs[def.Ref]
				if !ok {
					return "", fmt.Errorf("ref type '%s' not found", def.Ref)
				}
				aliasType, err := getDefTypeName(refDef, defs)
				if err != nil {
					return "", fmt.Errorf("failed to generate alias %s: %w", defName, err)
				}
				// Add description comment if available
				if def.Description != nil && *def.Description != "" {
					output.WriteString(fmt.Sprintf("# %s\n", *def.Description))
				}
				// Add SSZ type information
				output.WriteString(fmt.Sprintf("# SSZ: alias of %s\n", def.Ref))
				output.WriteString(fmt.Sprintf("%s = %s\n\n\n", defName, aliasType))
			}
		default:
			// Skip standard bytes types (bytes4, bytes20, bytes32, bytes48, bytes96) as they're imported
			if isBytesType(def) && isStandardBytesSize(def.Size) {
				// Skip - these are imported from ssz.sedes
				continue
			}

			// For basic types, generate as type alias if it's a named type
			// (e.g., Root = bytes32)
			baseType, err := getDefTypeName(def, defs)
			if err != nil {
				return "", fmt.Errorf("failed to generate type %s: %w", defName, err)
			}
			// Add description comment if available
			if def.Description != nil && *def.Description != "" {
				output.WriteString(fmt.Sprintf("# %s\n", *def.Description))
			}
			// Add SSZ type information
			sszInfo := buildSSZTypeComment(def)
			output.WriteString(fmt.Sprintf("# %s\n", sszInfo))
			output.WriteString(fmt.Sprintf("%s = %s\n\n\n", defName, baseType))
		}
	}

	return output.String(), nil
}

// importSet tracks which imports are needed
type importSet struct {
	containers map[string]bool // HashableContainer, SignedHashableContainer
	sedes      map[string]bool // uint64, bytes32, List, Vector, etc.
}

// collectImports analyzes all defs and determines which imports are needed
func collectImports(defs map[string]cuessz.Def) importSet {
	imports := importSet{
		containers: make(map[string]bool),
		sedes:      make(map[string]bool),
	}

	for _, def := range defs {
		collectImportsForDef(def, defs, &imports)
	}

	return imports
}

// collectImportsForDef recursively collects imports for a single def
func collectImportsForDef(def cuessz.Def, defs map[string]cuessz.Def, imports *importSet) {
	switch def.Type {
	case cuessz.TypeContainer, cuessz.TypeProgressiveContainer:
		// Determine if this is a signed container
		if hasSignatureField(def) {
			imports.containers["SignedHashableContainer"] = true
		} else {
			imports.containers["HashableContainer"] = true
		}

		// Collect imports from children
		for _, child := range def.Children {
			collectImportsForDef(child.Def, defs, imports)
		}

	case cuessz.TypeBoolean:
		imports.sedes["boolean"] = true

	case cuessz.TypeUint8:
		imports.sedes["uint8"] = true

	case cuessz.TypeUint16:
		imports.sedes["uint16"] = true

	case cuessz.TypeUint32:
		imports.sedes["uint32"] = true

	case cuessz.TypeUint64:
		imports.sedes["uint64"] = true

	case cuessz.TypeUint128:
		imports.sedes["uint128"] = true

	case cuessz.TypeUint256:
		imports.sedes["uint256"] = true

	case cuessz.TypeBitVector:
		imports.sedes["Bitvector"] = true

	case cuessz.TypeBitList:
		imports.sedes["Bitlist"] = true

	case cuessz.TypeVector:
		// Check if this is a bytesN type (vector of uint8)
		if isBytesType(def) {
			// Add the bytesN type to imports if it's a standard size
			bytesTypeName := fmt.Sprintf("bytes%d", def.Size)
			if isStandardBytesSize(def.Size) {
				imports.sedes[bytesTypeName] = true
			}
		} else {
			imports.sedes["Vector"] = true
			if len(def.Children) > 0 {
				collectImportsForDef(def.Children[0].Def, defs, imports)
			}
		}

	case cuessz.TypeList:
		imports.sedes["List"] = true
		if len(def.Children) > 0 {
			collectImportsForDef(def.Children[0].Def, defs, imports)
		}

	case cuessz.TypeRef:
		if def.Ref != "" {
			if refDef, ok := defs[def.Ref]; ok {
				collectImportsForDef(refDef, defs, imports)
			}
		}
	}

	// Check for specific byte sizes
	if strings.HasPrefix(string(def.Type), "bytes") {
		// Extract the byte size (e.g., "bytes32" -> need bytes32 import)
		imports.sedes[string(def.Type)] = true
	}
}

// hasSignatureField checks if a container has a field named "signature"
func hasSignatureField(def cuessz.Def) bool {
	for _, child := range def.Children {
		if child.Name == "signature" {
			return true
		}
	}
	return false
}

// isBytesType checks if a def is a vector of uint8 (i.e., a bytes type)
func isBytesType(def cuessz.Def) bool {
	if def.Type != cuessz.TypeVector {
		return false
	}
	if len(def.Children) == 0 {
		return false
	}
	return def.Children[0].Def.Type == cuessz.TypeUint8
}

// isStandardBytesSize checks if a size is a standard bytes size that py-ssz provides
// Standard sizes: 4, 20, 32, 48, 96
func isStandardBytesSize(size uint64) bool {
	switch size {
	case 4, 20, 32, 48, 96:
		return true
	default:
		return false
	}
}

// generateClass generates a Python class for a container
func generateClass(output *strings.Builder, defName string, def cuessz.Def, defs map[string]cuessz.Def) error {
	// Add type description comment if available
	if def.Description != nil && *def.Description != "" {
		output.WriteString(fmt.Sprintf("# %s\n", *def.Description))
	}

	// Determine base class
	baseClass := "HashableContainer"
	if hasSignatureField(def) {
		baseClass = "SignedHashableContainer"
	}

	// Class definition
	output.WriteString(fmt.Sprintf("class %s(%s):\n", defName, baseClass))

	// Build fields list
	output.WriteString("    fields = [\n")

	for _, child := range def.Children {
		// Get field type
		fieldType, err := getFieldTypeName(child, defs)
		if err != nil {
			return fmt.Errorf("failed to get type for field %s: %w", child.Name, err)
		}

		// Add field with optional comment
		if child.Description != nil && *child.Description != "" {
			output.WriteString(fmt.Sprintf("        # %s\n", *child.Description))
		}
		output.WriteString(fmt.Sprintf("        (\"%s\", %s),\n", child.Name, fieldType))
	}

	output.WriteString("    ]\n\n\n")

	return nil
}

// getFieldTypeName returns the Python type name for a field
func getFieldTypeName(field cuessz.Field, defs map[string]cuessz.Def) (string, error) {
	return getDefTypeName(field.Def, defs)
}

// getDefTypeName returns the Python type name for a def
func getDefTypeName(def cuessz.Def, defs map[string]cuessz.Def) (string, error) {
	switch def.Type {
	case cuessz.TypeBoolean:
		return "boolean", nil

	case cuessz.TypeUint8:
		return "uint8", nil

	case cuessz.TypeUint16:
		return "uint16", nil

	case cuessz.TypeUint32:
		return "uint32", nil

	case cuessz.TypeUint64:
		return "uint64", nil

	case cuessz.TypeUint128:
		return "uint128", nil

	case cuessz.TypeUint256:
		return "uint256", nil

	case cuessz.TypeBitVector:
		// Bitvector(size)
		return fmt.Sprintf("Bitvector(%d)", def.Size), nil

	case cuessz.TypeBitList:
		// Bitlist(limit)
		return fmt.Sprintf("Bitlist(%d)", def.Limit), nil

	case cuessz.TypeVector:
		// Check if this is a standard bytes type
		if isBytesType(def) && isStandardBytesSize(def.Size) {
			return fmt.Sprintf("bytes%d", def.Size), nil
		}
		// Vector(element_type, size)
		if len(def.Children) == 0 {
			return "", fmt.Errorf("vector missing element type")
		}
		elemType, err := getFieldTypeName(def.Children[0], defs)
		if err != nil {
			return "", err
		}
		return fmt.Sprintf("Vector(%s, %d)", elemType, def.Size), nil

	case cuessz.TypeList:
		// List(element_type, limit)
		if len(def.Children) == 0 {
			return "", fmt.Errorf("list missing element type")
		}
		elemType, err := getFieldTypeName(def.Children[0], defs)
		if err != nil {
			return "", err
		}
		return fmt.Sprintf("List(%s, %d)", elemType, def.Limit), nil

	case cuessz.TypeContainer, cuessz.TypeProgressiveContainer:
		// This shouldn't happen in practice as named containers are referenced by name
		return "object", nil

	case cuessz.TypeRef:
		// Reference to another type
		if def.Ref == "" {
			return "", fmt.Errorf("def has type 'ref' but no ref specified")
		}
		// Just use the type name directly
		return def.Ref, nil

	case cuessz.TypeUnion:
		// Unions are not directly supported in py-ssz
		return "object", nil

	default:
		// Check if it's a bytes type (bytes4, bytes32, bytes48, bytes96, etc.)
		typeStr := string(def.Type)
		if strings.HasPrefix(typeStr, "bytes") && len(typeStr) > 5 {
			// It's a specific byte size like bytes32
			return typeStr, nil
		}
		return "", fmt.Errorf("unknown type: %s", def.Type)
	}
}

// buildSSZTypeComment creates a comment describing the SSZ type information
func buildSSZTypeComment(def cuessz.Def) string {
	switch def.Type {
	case cuessz.TypeContainer:
		return "SSZ: container"
	case cuessz.TypeProgressiveContainer:
		if len(def.ActiveFields) > 0 {
			var bitset strings.Builder
			for _, bit := range def.ActiveFields {
				bitset.WriteString(fmt.Sprintf("%d", bit))
			}
			return fmt.Sprintf("SSZ: progressive_container, active_fields: %s", bitset.String())
		}
		return "SSZ: progressive_container"
	case cuessz.TypeVector:
		elemType := "uint8"
		if len(def.Children) > 0 {
			elemType = string(def.Children[0].Def.Type)
		}
		return fmt.Sprintf("SSZ: vector[%d] of %s", def.Size, elemType)
	case cuessz.TypeList:
		elemType := "uint8"
		if len(def.Children) > 0 {
			elemType = string(def.Children[0].Def.Type)
		}
		return fmt.Sprintf("SSZ: list[max=%d] of %s", def.Limit, elemType)
	case cuessz.TypeBitVector:
		return fmt.Sprintf("SSZ: bitvector[%d]", def.Size)
	case cuessz.TypeBitList:
		return fmt.Sprintf("SSZ: bitlist[max=%d]", def.Limit)
	default:
		return fmt.Sprintf("SSZ: %s", def.Type)
	}
}
